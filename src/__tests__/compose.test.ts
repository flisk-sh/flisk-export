describe("buildCompose restart, dependsOn conditions and buildArgs", () => {
  it("writes no restart when service.json has none, as the project's Compose file had it (pl_mail database)", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({ appName: "database", image: "postgres:18" }),
      res({ appName: "job", image: "i", restart: "no" }),
    ]);
    expect(text.slice(text.indexOf("  database:"), text.indexOf("  job:"))).not.toContain(
      "restart",
    );
    expect(text).toContain('  job:\n    image: "i"\n    init: true\n    restart: "no"\n');
  });

  it("writes a stated dependsOn condition, and service_started for service_healthy without a healthcheck", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({
        appName: "web",
        image: "i",
        dependsOn: [
          "cache",
          { name: "db", condition: "service_healthy" },
          { name: "migrate", condition: "service_completed_successfully" },
          { name: "plain", condition: "service_healthy" },
          { name: "gone", condition: "service_started" },
        ],
      }),
      res({ appName: "cache", image: "i" }),
      res({ appName: "db", image: "i", healthCheck: { command: ["pg_isready"] } }),
      res({ appName: "migrate", image: "i" }),
      res({ appName: "plain", image: "i" }),
    ]);
    expect(text).toContain(
      "    depends_on:\n      cache:\n        condition: service_started\n      db:\n        condition: service_healthy\n      migrate:\n        condition: service_completed_successfully\n      plain:\n        condition: service_started\n",
    );
    expect(text).not.toContain("gone");
  });

  it("refuses a condition Compose does not have", () => {
    expect(() =>
      buildCompose("/p/.autogenerated", [
        res({ appName: "web", image: "i", dependsOn: [{ name: "db", condition: "always\nx: 1" }] }),
        res({ appName: "db", image: "i" }),
      ]),
    ).toThrow(/is not a Compose condition/);
  });

  it("writes buildArgs as build.args and refuses names that could add keys", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({
        appName: "database",
        buildContext: ".",
        dockerfile: "Dockerfile",
        buildArgs: { POSTGRES_VERSION: "${POSTGRES_VERSION:-18}" },
      }),
    ]);
    expect(text).toContain(
      '      dockerfile: "Dockerfile"\n      args:\n        POSTGRES_VERSION: "${POSTGRES_VERSION:-18}"\n',
    );
    expect(() =>
      buildCompose("/p/.autogenerated", [
        res({ appName: "a", dockerfile: "Dockerfile", buildArgs: { "X\ny": "1" } }),
      ]),
    ).toThrow(/buildArgs/);
  });
});
