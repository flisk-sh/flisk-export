import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { describe, expect, it } from "vitest";
import { buildCompose } from "../compose.js";
import type { Resource } from "../discover.js";
import { main } from "../main.js";

function res(config: Record<string, unknown>, dir = "/p/services/s/x"): Resource {
  return {
    name: String(config.appName),
    path: dir,
    type: String(config.appType ?? "bring-your-own"),
    config,
  };
}

function project(files: Record<string, unknown>): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-compose-"));
  fs.mkdirSync(path.join(root, ".flisk"));
  fs.writeFileSync(path.join(root, ".flisk/project.json"), "{}");
  for (const [rel, config] of Object.entries(files)) {
    const file = path.join(root, rel, "service.json");
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(config));
  }
  return fs.realpathSync(root);
}

async function run(args: string[], cwd: string) {
  let out = "";
  let err = "";
  const code = await main(args, { cwd, out: (t) => (out += t), err: (t) => (err += t) });
  return { code, out, err };
}

describe("buildCompose volume names", () => {
  it("declares a named volume with its Docker name so an install's data is reused", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({
        appName: "db",
        image: "i",
        volumes: [{ source: "pg", target: "/d", name: "nosia_pg" }],
      }),
      res({
        appName: "b",
        image: "i",
        volumes: [
          { source: "pg", target: "/r" },
          { source: "x", target: "/x" },
        ],
      }),
    ]);
    expect(text).toContain('volumes:\n  pg:\n    name: "nosia_pg"\n  x:\n');
  });

  it("names the Compose project after the one stack", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({ appName: "a", image: "i", stack: "nosia" }),
    ]);
    expect(text).toContain('\nname: "nosia"\n\nservices:');
  });

  it("refuses two names for one volume", () => {
    expect(() =>
      buildCompose("/p/.autogenerated", [
        res({ appName: "a", image: "i", volumes: [{ source: "pg", target: "/d", name: "one" }] }),
        res({ appName: "b", image: "i", volumes: [{ source: "pg", target: "/d", name: "two" }] }),
      ]),
    ).toThrow(/two names/);
  });
});

