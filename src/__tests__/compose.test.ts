describe("buildCompose secrets, health and conditions", () => {
  const db = res({
    appName: "db",
    appType: "bring-your-own",
    image: "postgres:16",
    healthCheck: { command: ["pg_isready", "-U", "app"], interval: 2, timeout: 5, retries: 30 },
    secrets: { required: ["POSTGRES_PASSWORD"] },
  });
  const migrate = res({
    appName: "migrate",
    appType: "bring-your-own",
    image: "app:1",
    restart: "no",
    dependsOn: ["db"],
    env: { A: "1" },
    secrets: { required: ["SECRET_KEY_BASE", "A"] },
  });
  const web = res({
    appName: "web",
    appType: "bring-your-own",
    image: "app:1",
    dependsOn: ["db", "migrate"],
    healthCheck: false,
  });

  it("passes required secrets through as ${NAME} and lets env win", () => {
    const text = buildCompose("/p/.autogenerated", [db, migrate, web]);
    expect(text).toContain('POSTGRES_PASSWORD: "${POSTGRES_PASSWORD}"');
    expect(text).toContain('SECRET_KEY_BASE: "${SECRET_KEY_BASE}"');
    expect(text).toContain('A: "1"');
    expect(text).not.toContain('A: "${A}"');
  });

  it("writes a healthcheck from healthCheck.command and disables it for false", () => {
    const text = buildCompose("/p/.autogenerated", [db, migrate, web]);
    expect(text).toContain(
      '    healthcheck:\n      test: ["CMD", "pg_isready", "-U", "app"]\n      interval: "2s"\n      timeout: "5s"\n      retries: 30',
    );
    expect(text).toContain("    healthcheck:\n      disable: true");
  });

  it("waits for a healthy check or a finished one-shot job", () => {
    const text = buildCompose("/p/.autogenerated", [db, migrate, web]);
    expect(text).toContain("      db:\n        condition: service_healthy");
    expect(text).toContain("      migrate:\n        condition: service_completed_successfully");
  });

  it("rejects a healthcheck interval that is not positive", () => {
    const bad = res({ appName: "x", image: "i", healthCheck: { command: ["true"], interval: 0 } });
    expect(() => buildCompose("/p/.autogenerated", [bad])).toThrow(/interval/);
  });
});

describe("buildCompose extraPorts publish", () => {
  it("writes publish as the host side and keeps bind", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({
        appName: "proxy",
        image: "caddy:2",
        extraPorts: [
          { port: 80, publish: "${APP_HTTP_BIND:-80}" },
          { port: 443, publish: "127.0.0.1:${APP_HTTPS_PORT:-8443}" },
          { port: 8080, publish: "192.168.1.10:8080", protocol: "udp" },
          { port: 9000, bind: "0.0.0.0" },
        ],
      }),
    ]);
    expect(text).toContain('- "${APP_HTTP_BIND:-80}:80/tcp"');
    expect(text).toContain('- "127.0.0.1:${APP_HTTPS_PORT:-8443}:443/tcp"');
    expect(text).toContain('- "192.168.1.10:8080:8080/udp"');
    expect(text).toContain('- "0.0.0.0:9000:9000/tcp"');
  });

  it.each([["${PORT}"], ['80"\n    privileged: true'], ["host:80"], [80]])(
    "refuses publish %j",
    (publish) => {
      expect(() =>
        buildCompose("/p/.autogenerated", [
          res({ appName: "proxy", image: "caddy:2", extraPorts: [{ port: 80, publish }] }),
        ]),
      ).toThrow(/publish must be/);
    },
  );

  it("refuses a bind other than 127.0.0.1 and 0.0.0.0", () => {
    expect(() =>
      buildCompose("/p/.autogenerated", [
        res({ appName: "proxy", image: "caddy:2", extraPorts: [{ port: 80, bind: "1.2.3.4" }] }),
      ]),
    ).toThrow(/bind must be/);
  });
});

describe("buildCompose", () => {
  it("maps image, env, restart, volumes, ports, dependsOn and container options", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({
        appName: "web",
        image: "caddy:2",
        env: { A: "${A:-x}" },
        restart: "no",
        dependsOn: ["db", "elsewhere"],
        extraPorts: [
          { port: 80, hostPort: 8080 },
          { port: 443, bind: "0.0.0.0" },
        ],
        volumes: [
          { source: "data", target: "/data" },
          { source: "../../../deploy/Caddyfile", target: "/etc/Caddyfile", readOnly: true },
        ],
        container: { capAdd: ["NET_ADMIN"], readOnly: true, user: "1:1", shmSize: "256mb" },
      }),
      res({ appName: "db", image: "postgres:14" }, "/p/services/s/db"),
    ]);
    expect(text).toContain('image: "caddy:2"');
    expect(text).toContain('A: "${A:-x}"');
    expect(text).toContain('restart: "no"');
    expect(text).toContain('"127.0.0.1:8080:80/tcp"');
    expect(text).toContain('"0.0.0.0:443:443/tcp"');
    expect(text).toContain('"data:/data"');
    expect(text).toContain('"../deploy/Caddyfile:/etc/Caddyfile:ro"');
    expect(text).toContain("cap_add:");
    expect(text).toContain("read_only: true");
    expect(text).toContain('shm_size: "256mb"');
    expect(text).toMatch(/depends_on:\n {6}db:\n {8}condition: service_started\n/);
    expect(text).not.toContain("elsewhere");
    expect(text).toMatch(/volumes:\n {2}data:\n/);
  });

  it("shares the network of a sidecarOf target", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({ appName: "main", image: "a" }),
      res({ appName: "side", image: "b", sidecarOf: "main" }),
    ]);
    expect(text).toContain('network_mode: "service:main"');
  });

  it("builds from the resource directory when there is no image", () => {
    const text = buildCompose("/p/.autogenerated", [
      res({ appName: "api", dockerfile: "Dockerfile.prod" }),
    ]);
    expect(text).toContain('context: "../services/s/x"');
    expect(text).toContain('dockerfile: "Dockerfile.prod"');
  });

  it("has no Flisk networks, variables or secrets", () => {
    const text = buildCompose("/p/.autogenerated", [res({ appName: "a", image: "i" })]);
    expect(text).not.toMatch(/external|FLISK_|networks:|NATS|DATABASE_URL/);
  });

  it("refuses a sidecar with ports, an unknown restart policy and no resources", () => {
    expect(() =>
      buildCompose("/p", [
        res({ appName: "m", image: "a" }),
        res({ appName: "s", image: "b", sidecarOf: "m", extraPorts: [{ port: 1 }] }),
      ]),
    ).toThrow(/cannot publish ports/);
    expect(() => buildCompose("/p", [res({ appName: "m", image: "a", restart: "x" })])).toThrow(
      /restart policy/,
    );
    expect(() => buildCompose("/p", [res({ appName: "m", appType: "backend" })])).toThrow(
      /No bring-your-own/,
    );
  });

  it("skips native command services", () => {
    expect(() => buildCompose("/p", [res({ appName: "n", command: "node x.js" })])).toThrow(
      /No bring-your-own/,
    );
  });
});

describe("flisk-export compose", () => {
  const files = {
    "services/a/web": { appName: "web", appType: "bring-your-own", image: "nginx" },
  };

  it("writes .autogenerated/docker-compose.yml, refuses to overwrite, then --check passes", async () => {
    const root = project(files);
    const first = await run(["compose", root], root);
    expect(first.code).toBe(0);
    const file = path.join(root, ".autogenerated/docker-compose.yml");
    expect(fs.readFileSync(file, "utf-8")).toContain("web:");
    expect((await run(["compose", root], root)).code).toBe(1);
    expect((await run(["compose", root, "--check"], root)).code).toBe(0);
  });

  it("--check fails when service.json changed or the file is missing; --dry-run writes nothing", async () => {
    const root = project(files);
    expect((await run(["compose", root, "--check"], root)).code).toBe(1);
    await run(["compose", root], root);
    fs.writeFileSync(
      path.join(root, "services/a/web/service.json"),
      JSON.stringify({ appName: "web", appType: "bring-your-own", image: "httpd" }),
    );
    const stale = await run(["compose", root, "--check"], root);
    expect(stale.code).toBe(1);
    expect(stale.err).toContain("out of date");
    const other = project(files);
    const dry = await run(["compose", other, "--dry-run"], other);
    expect(dry.code).toBe(0);
    expect(fs.existsSync(path.join(other, ".autogenerated"))).toBe(false);
  });
});
